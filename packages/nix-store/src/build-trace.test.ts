import { describe, expect, it } from 'vitest';

import { BuildTrace, InvalidBuildTraceError } from './build-trace.ts';
import { NixTrustedKeys } from './verify.ts';

// Nix 2.35.2 generated this record and signature in an isolated local store.
const nativeTrace = {
	key: {
		drvPath:
			'nfhl9kzx1i1fy6s1dsmm7f7431fvjn7j-cupboard-signed-trace-fixture.drv',
		outputName: 'out'
	},
	value: {
		outPath: 'v8wgiskw026fg9nwnqzdwyhz242x4diw-cupboard-signed-trace-fixture',
		signatures: [
			{
				keyName: 'cupboard-trace-fixture-1',
				sig: '+IRS0ktgNcLlMsgFbzCpCbG7HNxaBHmAaWRAq5THSz4ghia8UkwF+wYn2Uy0eefdnb+9V73CbcDN9a2vqXlDCA=='
			}
		]
	}
};
const publicKey =
	'cupboard-trace-fixture-1:1fQlazdsf0soobDv2ceK6TeEX6IViNJTJwGW9E36GT8=';
const fingerprint =
	'{"key":{"drvPath":"nfhl9kzx1i1fy6s1dsmm7f7431fvjn7j-cupboard-signed-trace-fixture.drv","outputName":"out"},"value":{"outPath":"v8wgiskw026fg9nwnqzdwyhz242x4diw-cupboard-signed-trace-fixture"}}';

describe('Nix 2.35 build traces', () => {
	it.each(['object', 'string'] as const)(
		'reads native %s signatures and emits a value-only .doi document',
		(format) => {
			const trace = new BuildTrace({
				...nativeTrace,
				value: {
					...nativeTrace.value,
					signatures:
						format === 'object'
							? nativeTrace.value.signatures
							: nativeTrace.value.signatures.map(
									({ keyName, sig }) => `${keyName}:${sig}`
								)
				}
			});
			const wireValue: unknown = JSON.parse(trace.renderValue());
			expect({
				key: trace.key,
				value: trace.value,
				path: trace.path,
				fingerprint: trace.fingerprint(),
				signatureValues: trace.signatureValues,
				wireValue
			}).toStrictEqual({
				...nativeTrace,
				path: 'build-trace-v2/nfhl9kzx1i1fy6s1dsmm7f7431fvjn7j-cupboard-signed-trace-fixture.drv/out.doi',
				fingerprint,
				signatureValues: nativeTrace.value.signatures.map(
					({ keyName, sig }) => `${keyName}:${sig}`
				),
				wireValue: nativeTrace.value
			});
		}
	);

	it('verifies the signature generated by native Nix', async () => {
		const trace = new BuildTrace(nativeTrace);
		await expect(
			NixTrustedKeys.of([publicKey]).hasValidSignature(
				trace.fingerprint(),
				trace.signatureValues
			)
		).resolves.toBe(true);
	});

	it.each([
		{
			field: 'derivation path',
			key: {
				...nativeTrace.key,
				drvPath: `0${nativeTrace.key.drvPath.slice(1)}`
			},
			value: nativeTrace.value
		},
		{
			field: 'output name',
			key: { ...nativeTrace.key, outputName: 'dev' },
			value: nativeTrace.value
		},
		{
			field: 'output path',
			key: nativeTrace.key,
			value: {
				...nativeTrace.value,
				outPath: `0${nativeTrace.value.outPath.slice(1)}`
			}
		}
	])(
		'rejects the signature after changing the $field',
		async ({ key, value }) => {
			const trace = new BuildTrace({ key, value });
			await expect(
				NixTrustedKeys.of([publicKey]).hasValidSignature(
					trace.fingerprint(),
					trace.signatureValues
				)
			).resolves.toBe(false);
		}
	);

	it('reads an unsigned trace when the signatures field is omitted', () => {
		const trace = new BuildTrace({
			key: nativeTrace.key,
			value: { outPath: nativeTrace.value.outPath }
		});
		expect(trace.value).toStrictEqual({
			outPath: nativeTrace.value.outPath,
			signatures: []
		});
	});

	it.each([
		{
			key: {
				...nativeTrace.key,
				drvPath: `/nix/store/${nativeTrace.key.drvPath}`
			},
			value: nativeTrace.value
		},
		{
			key: { ...nativeTrace.key, outputName: '../out' },
			value: nativeTrace.value
		},
		{ key: { ...nativeTrace.key, outputName: '' }, value: nativeTrace.value },
		{
			key: nativeTrace.key,
			value: { ...nativeTrace.value, outPath: '/nix/store/invalid' }
		},
		{
			key: nativeTrace.key,
			value: { ...nativeTrace.value, signatures: ['malformed'] }
		}
	])('refuses malformed trace data: %j', (entry) => {
		expect(() => new BuildTrace(entry)).toThrow(InvalidBuildTraceError);
	});
});
