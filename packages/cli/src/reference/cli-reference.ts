import type { Command } from 'commander';

// Wrap help to a fixed width and render it without colour, so the reference
// comes out the same whatever terminal regenerates it.
const helpWidth = 80;

const preamble = `<!-- Generated by \`pnpm update:cli-reference\` from the command definitions. Do not edit by hand. -->

# CLI reference

This page is the \`--help\` output of every \`cupboard\` command. The guides
under [docs/](../README.md) explain when to use each one.`;

interface ReferenceEntry {
	readonly path: readonly string[];
	readonly command: Command;
}

function* walk(
	command: Command,
	path: readonly string[]
): Generator<ReferenceEntry> {
	yield { path, command };

	for (const child of command.commands) {
		// Skip commander's built-in `help` command, which isn't a cupboard command.
		if (child.name() === 'help') {
			continue;
		}

		yield* walk(child, [...path, child.name()]);
	}
}

function renderedHelp(command: Command): string {
	let captured = '';

	command.configureHelp({ helpWidth });
	command.configureOutput({
		getOutHasColors: () => false,
		writeOut: (text) => {
			captured += text;
		}
	});
	// `helpInformation()` leaves out text added with `addHelpText`, which is
	// only written when help is output, so capture the output instead.
	command.outputHelp();

	return captured.trimEnd();
}

function anchorFor(path: readonly string[]): string {
	return path.join('-');
}

function renderIndex(entries: readonly ReferenceEntry[]): string {
	return entries
		.slice(1)
		.map(({ path }) => {
			const indent = '  '.repeat(path.length - 2);

			return `${indent}- [\`${path.join(' ')}\`](#${anchorFor(path)})`;
		})
		.join('\n');
}

function renderEntry({ path, command }: ReferenceEntry): string {
	const depth = Math.min(path.length + 1, 6);

	return [
		`${'#'.repeat(depth)} ${path.join(' ')}`,
		'',
		'```text',
		renderedHelp(command),
		'```'
	].join('\n');
}

/**
 * Renders the Markdown CLI reference for a newly built program. Rendering
 * changes where each command writes its help, so pass a program built just for
 * this, not one that will go on to parse arguments.
 */
export function renderCliReference(program: Command): string {
	const entries = [...walk(program, [program.name()])];

	return `${[preamble, renderIndex(entries), ...entries.map((entry) => renderEntry(entry))].join('\n\n')}\n`;
}
